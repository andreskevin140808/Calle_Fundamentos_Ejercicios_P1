public class T1_Taller {
    public static void main(String[] args) {

        System.out.println("1) 5 + 7 / 2 * 3 = "
                + (5 + 7 / 2 * 3));

        System.out.println("2) (5 + 7) / 2.0 * 3 = "
                + ((5 + 7) / 2.0 * 3));

        System.out.println("3) 17 % 4 + 2 * 3 - 1 = "
                + (17 % 4 + 2 * 3 - 1));

        System.out.println("4) (int) 7.9 + 7 / 2 = "
                + ((int) 7.9 + 7 / 2));

        System.out.println("5) 8 > 3 && 2 != 2 || !(5 < 1) = "
                + (8 > 3 && 2 != 2 || !(5 < 1)));

        System.out.println("6a) 'A' + 2 = "
                + ('A' + 2));

        System.out.println("6b) (char) ('A' + 2) = "
                + ((char) ('A' + 2)));
    }
}